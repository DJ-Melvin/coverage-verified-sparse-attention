#!/usr/bin/env python3
"""Build the full RULER appendix table.

Outputs:
  1. results/tables/ruler_full.tex
  2. results/tables/ruler_full.md
"""
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(REPO)

MODELS = {
    "Llama-3.1-8B": (
        "results/ruler_final_llama.json",
        "results/ruler_longctx_llama.json",
        "results/ruler_longctx_eviction_llama.json",
    ),
    "Mistral-7B": (
        "results/ruler_final_mistral.json",
        "results/ruler_longctx_mistral.json",
        "results/ruler_longctx_eviction_mistral.json",
    ),
    "Qwen-7B": (
        "results/ruler_final_qwen.json",
        "results/ruler_longctx_qwen.json",
        "results/ruler_longctx_eviction_qwen.json",
    ),
}

CONTEXTS = [4096, 8192, 16384, 32768, 65536, 131072]
CONTEXT_LABELS = {
    4096: "4K",
    8192: "8K",
    16384: "16K",
    32768: "32K",
    65536: "64K",
    131072: "128K",
}

TASKS = ["s_niah", "mk_niah", "mv_niah", "mq_niah", "vt", "cwe"]
TASK_LABELS = {
    "s_niah": "S-NIAH",
    "mk_niah": "MK-NIAH",
    "mv_niah": "MV-NIAH",
    "mq_niah": "MQ-NIAH",
    "vt": "VT",
    "cwe": "CWE",
}

# Second field: method key stored in results/ruler_*.json (historical ssa_* prefix).
METHODS = [
    ("Dense", "dense"),
    ("CVSA-c4", "ssa_5_90_c4_ar20_dL0"),
    ("CVSA-c8", "ssa_5_90_c8_ar20_dL0"),
    ("SnapKV", "snapkv_10"),
    ("H2O", "h2o_10"),
    ("Ada-KV", "adakv_10"),
    ("Fixed-10%", "fixed_10"),
]


def load_model(paths):
    merged = {}
    for path in paths:
        if not os.path.exists(path):
            continue
        with open(path) as f:
            data = json.load(f)
        for method, method_results in data.get("results", {}).items():
            merged.setdefault(method, {})
            for task, task_results in method_results.items():
                merged[method].setdefault(task, {})
                for ctx, value in task_results.items():
                    merged[method][task][int(ctx)] = value
    return merged


def get_val(data, method_key, task, ctx):
    return data.get(method_key, {}).get(task, {}).get(ctx)


def best_method_index(row_vals, exclude_indices=None):
    exclude_indices = exclude_indices or set()
    best_i, best_v = None, -float("inf")
    for i, value in enumerate(row_vals):
        if i in exclude_indices or value is None:
            continue
        if value > best_v:
            best_i, best_v = i, value
    return best_i


def fmt_cell(value, bold=False, latex=True):
    if value is None:
        return "\\textendash" if latex else "--"
    text = f"{value:.1f}"
    if bold:
        return f"\\textbf{{{text}}}" if latex else f"**{text}**"
    return text


def latex_table():
    lines = [
        "% Auto-generated by eval/build_ruler_table.py -- do not edit directly.",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Complete RULER accuracy (\\%, 10 trials through 32K and 5 trials at 64K--128K). "
        "Rows = (task, context); columns = methods. "
        "Bold = highest among non-Dense methods per row.}",
        "\\label{tab:ruler_full}",
        "\\tiny",
    ]

    for model_name, paths in MODELS.items():
        data = load_model(paths)
        lines.extend([
            "",
            f"\\subcaption*{{\\textbf{{{model_name}}}}}",
            "\\begin{tabular}{ll ccccccc}",
            "\\toprule",
            "Task & Context & " + " & ".join(label for label, _ in METHODS) + " \\\\",
            "\\midrule",
        ])

        for task_i, task in enumerate(TASKS):
            for ctx_i, ctx in enumerate(CONTEXTS):
                row_vals = [get_val(data, key, task, ctx) for _, key in METHODS]
                best_i = best_method_index(row_vals, exclude_indices={0})
                cells = [
                    fmt_cell(value, bold=(i == best_i), latex=True)
                    for i, value in enumerate(row_vals)
                ]
                task_cell = TASK_LABELS[task] if ctx_i == 0 else ""
                lines.append(
                    f"{task_cell} & {CONTEXT_LABELS[ctx]} & "
                    + " & ".join(cells)
                    + " \\\\"
                )
            if task_i < len(TASKS) - 1:
                lines.append("\\midrule")

        lines.extend(["\\bottomrule", "\\end{tabular}", "\\vspace{0.8em}"])

    lines.append("\\end{table}")
    return "\n".join(lines)


def markdown_tables():
    lines = [
        "# RULER Full Results (6 tasks x 6 contexts x 3 models x 7 methods)",
        "",
        "> Auto-generated from `results/ruler_final_*.json`, "
        "`results/ruler_longctx_*.json`, and "
        "`results/ruler_longctx_eviction_*.json`.",
        "> `*` marks the highest-scoring non-Dense method per row. `--` = not measured.",
        "",
    ]

    for model_name, paths in MODELS.items():
        data = load_model(paths)
        lines.extend([
            f"## {model_name}",
            "",
            "| Task | Context | " + " | ".join(label for label, _ in METHODS) + " |",
            "|------|---------|" + "|".join(["------"] * len(METHODS)) + "|",
        ])
        for task in TASKS:
            for ctx_i, ctx in enumerate(CONTEXTS):
                row_vals = [get_val(data, key, task, ctx) for _, key in METHODS]
                best_i = best_method_index(row_vals, exclude_indices={0})
                cells = [
                    fmt_cell(value, bold=(i == best_i), latex=False)
                    for i, value in enumerate(row_vals)
                ]
                task_cell = TASK_LABELS[task] if ctx_i == 0 else ""
                lines.append(
                    f"| {task_cell} | {CONTEXT_LABELS[ctx]} | "
                    + " | ".join(cells)
                    + " |"
                )
        lines.append("")
    return "\n".join(lines)


def mean_gap_to_dense(datas, method_key, contexts):
    """Mean accuracy gap to dense over every (model, task, context) cell both were run on."""
    gaps = []
    for data in datas:
        for task in TASKS:
            for ctx in contexts:
                v = get_val(data, method_key, task, ctx)
                d = get_val(data, "dense", task, ctx)
                if v is not None and d is not None:
                    gaps.append(v - d)
    return (sum(gaps) / len(gaps), len(gaps)) if gaps else (None, 0)


def appendix_tables():
    """RULER appendix tables: a gap-to-dense summary plus one full table per model.

    No cell is bolded (ties are frequent at these trial counts), and labels are
    LaTeX-safe ("Fixed-10\\%").
    """
    names = {"Llama-3.1-8B": "Llama-3.1-8B", "Mistral-7B": "Mistral-7B-v0.3", "Qwen-7B": "Qwen2.5-7B"}
    # \ssa{} is the paper's LaTeX macro for the method name (renders CVSA).
    tex_label = {"CVSA-c4": "\\ssa{}-c4", "CVSA-c8": "\\ssa{}-c8", "Ada-KV": "AdaKV", "Fixed-10%": "Fixed-10\\%"}
    header = " & ".join(tex_label.get(label, label) for label, _ in METHODS)
    datas = {m: load_model(paths) for m, paths in MODELS.items()}
    short = [c for c in CONTEXTS if c <= 32768]

    lines = [
        "% Auto-generated by eval/build_ruler_table.py -- do not edit directly.",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\small",
        "  \\caption{Mean RULER accuracy gap to dense (points), averaged over the six tasks and three models. "
        "The 4K--32K column covers every method on the same 72 cells and is the basis of the RULER numbers in the main text; "
        "the second column adds the 64K and 128K cells each method was run on (cell counts in parentheses).}",
        "  \\label{tab:ruler-summary}",
        "  \\begin{tabular}{@{}lcc@{}}",
        "    \\toprule",
        "    Method & 4K--32K & All measured contexts \\\\",
        "    \\midrule",
    ]
    for label, key in METHODS[1:]:
        g1, n1 = mean_gap_to_dense(datas.values(), key, short)
        g2, n2 = mean_gap_to_dense(datas.values(), key, CONTEXTS)
        lines.append(f"    {tex_label.get(label, label)} & ${g1:+.2f}$ ({n1}) & ${g2:+.2f}$ ({n2}) \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]

    for model_name, data in datas.items():
        lines += [
            "\\begin{table}[!t]",
            "  \\centering",
            "  \\footnotesize",
            "  \\setlength{\\tabcolsep}{4pt}",
            f"  \\caption{{RULER accuracy (\\%) on {names[model_name]}. Through 32K each cell averages 10 trials, "
            "at 64K and 128K five; ``--'' marks a setting not run. Baselines use a $10\\%$ budget.}",
            f"  \\label{{tab:ruler-full-{model_name.split('-')[0].lower()}}}",
            "  \\begin{tabular}{@{}ll" + "c" * len(METHODS) + "@{}}",
            "    \\toprule",
            f"    Task & Context & {header} \\\\",
            "    \\midrule",
        ]
        for task_i, task in enumerate(TASKS):
            for ctx_i, ctx in enumerate(CONTEXTS):
                cells = [get_val(data, key, task, ctx) for _, key in METHODS]
                cells = ["--" if v is None else f"{v:.1f}" for v in cells]
                task_cell = TASK_LABELS[task] if ctx_i == 0 else ""
                lines.append(f"    {task_cell} & {CONTEXT_LABELS[ctx]} & " + " & ".join(cells) + " \\\\")
            lines.append("    \\midrule" if task_i < len(TASKS) - 1 else "    \\bottomrule")
        lines += ["  \\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main():
    os.makedirs("results/tables", exist_ok=True)

    apx = appendix_tables()
    apx_path = "results/tables/ruler_appendix.tex"
    # newline="\n": the committed outputs are LF; keep them byte-identical on any OS.
    with open(apx_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(apx + "\n")
    print(f"Wrote {apx_path} ({len(apx.splitlines())} lines)")

    tex = latex_table()
    tex_path = "results/tables/ruler_full.tex"
    with open(tex_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(tex + "\n")
    print(f"Wrote {tex_path} ({len(tex.splitlines())} lines)")

    md = markdown_tables()
    md_path = "results/tables/ruler_full.md"
    with open(md_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(md + "\n")
    print(f"Wrote {md_path} ({len(md.splitlines())} lines)")


if __name__ == "__main__":
    main()
